import { expect, test } from "@playwright/test"

test("quoted goal stays in the phone composer until the quotation is removed", async ({ page }, info) => {
  await page.goto("/?mock=1&tick=0")
  const input = page.getByLabel("消息", { exact: true })
  await input.fill("show result")
  await page.getByRole("button", { name: /跟进|发送/ }).click()
  const source = page.getByTestId("transcript").getByText("Here is what changed:")
  await expect(source).toBeVisible()
  await source.evaluate((element) => {
    const range = document.createRange()
    range.selectNodeContents(element)
    window.getSelection()?.removeAllRanges()
    window.getSelection()?.addRange(range)
    document.dispatchEvent(new Event("selectionchange"))
  })
  await page.getByRole("button", { name: "加入对话" }).click()
  await expect(page.getByTestId("quote-draft")).toHaveValue("Here is what changed:")
  const command = "/goal Inspect the assigned operation"
  await input.fill(command)
  const before = await page.getByTestId("quoted-message").count()
  await page.getByRole("button", { name: /跟进|发送/ }).click()
  await expect(page.getByRole("alert")).toContainText("命令只接受纯文本")
  await expect(input).toHaveValue(command)
  await expect(page.getByTestId("quote-draft")).toHaveValue("Here is what changed:")
  await expect(page.getByTestId("quoted-message")).toHaveCount(before)
  await page.screenshot({ path: info.outputPath("quoted-goal-refused-draft-kept.png") })
  await page.getByRole("button", { name: /移除引用/ }).click()
  await expect(page.getByRole("alert")).toHaveCount(0)
  await input.press("Enter")
  await expect(input).toHaveValue("")
  await expect(page.getByTestId("transcript")).toContainText(command)
  await page.screenshot({ path: info.outputPath("plain-goal-submitted.png") })
})
