import { expect, test } from "@playwright/test"

test("phone creates a PC project, edits it and starts a conversation in it", async ({ page }, info) => {
 await page.goto("/?mock=1&tick=0")
 await page.getByRole("button", {name:"返回",exact:true}).click()
 await page.getByRole("button", {name:"菜单",exact:true}).click()
 await page.getByRole("menuitem", {name:"项目管理",exact:true}).click()
 const panel = page.getByRole("dialog",{name:"项目管理"})
 await panel.getByRole("button",{name:"新建项目",exact:true}).click()
 await panel.getByRole("textbox",{name:"项目名称",exact:true}).fill("Mobile project")
 await panel.getByRole("textbox",{name:"项目指令",exact:true}).fill("Shared instructions")
 await panel.getByRole("checkbox",{name:"女娲协作",exact:true}).check()
 await expect(panel.getByRole("combobox",{name:"规划模型",exact:true})).toContainText("scripted")
 await expect(panel.getByRole("combobox",{name:"执行模型",exact:true})).toContainText("scripted")
 await page.setViewportSize({width:320,height:844})
 await expect(panel).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
 await page.screenshot({path:info.outputPath("project-editor.png")})
 await panel.getByRole("button",{name:"创建项目",exact:true}).click()
 await expect(panel.getByRole("status")).toHaveText("项目已保存。")
 await panel.getByRole("button",{name:"Mobile project",exact:true}).click()
 await expect(panel.getByRole("textbox",{name:"项目指令",exact:true})).toHaveValue("Shared instructions")
 await panel.getByRole("textbox",{name:"项目名称",exact:true}).fill("Phone managed")
 await panel.getByRole("button",{name:"保存项目",exact:true}).click()
 await panel.getByRole("button",{name:"关闭",exact:true}).click()
 await expect(page.getByText("Phone managed",{exact:true})).toBeVisible()
 await page.getByTestId("new-chat-top").click()
 await page.getByRole("radio",{name:"Phone managed",exact:true}).click()
 await page.getByRole("button",{name:"项目管理",exact:true}).click()
 await panel.getByRole("button",{name:"新建项目",exact:true}).click()
 await panel.getByRole("textbox",{name:"项目名称",exact:true}).fill("From composer")
 await panel.getByRole("button",{name:"创建项目",exact:true}).click()
 await panel.getByRole("button",{name:"关闭",exact:true}).click()
 await expect(page.getByRole("radio",{name:"From composer",exact:true})).toBeChecked()
 await page.getByRole("textbox", {name:"新消息",exact:true}).fill("Check selected project")
 await page.getByRole("button",{name:"开始",exact:true}).click()
 await expect(page.getByText("Check selected project",{exact:true}).first()).toBeVisible()
})

test("a refused project save keeps the draft and close returns to the inbox",async({page})=>{
 await page.goto("/?mock=1&tick=0&projects=save-fail")
 await page.getByRole("button",{name:"返回",exact:true}).click()
 await page.getByRole("button",{name:"菜单",exact:true}).click()
 await page.getByRole("menuitem",{name:"项目管理",exact:true}).click()
 const panel=page.getByRole("dialog",{name:"项目管理"})
 await panel.getByRole("button",{name:"Field notes",exact:true}).click()
 await panel.getByRole("textbox",{name:"项目指令",exact:true}).fill("Retained draft")
 await panel.getByRole("button",{name:"保存项目",exact:true}).click()
 await expect(panel.getByRole("alert")).toHaveText("Could not save project")
 await expect(panel.getByRole("textbox",{name:"项目指令",exact:true})).toHaveValue("Retained draft")
 await panel.getByRole("button",{name:"关闭",exact:true}).click()
 await expect(page.getByTestId("inbox-list")).toBeVisible()
})
