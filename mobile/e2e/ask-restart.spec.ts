import { expect, test } from "@playwright/test"

test("a recovered original question stays answerable through history and settles once", async ({ page }, info) => {
  await page.addInitScript(() => localStorage.setItem("zwai.phone.locale", "en"))
  await page.goto("/?mock=1&history=restart-ask&tick=0")
  const card = page.getByTestId("ask-card")
  await expect(card).toHaveCount(1)
  await expect(card).toContainText("When should this run?")
  await expect(card.getByRole("button", { name: "Now", exact: true })).toBeVisible()
  await expect(page.getByTestId("transcript")).not.toContainText("private seed")
  // WebKit may expose the DOM before the native compositor finishes the screen push.
  await expect(page.locator(".screen-push")).toHaveCSS("opacity", "1")
  await expect(page.locator(".screen-push")).toHaveCSS("transform", /^(none|matrix\(1, 0, 0, 1, 0, 0\))$/)
  await page.screenshot({ path: info.outputPath("original-ask-replayed.png"), animations: "disabled" })
  const title = await page.getByRole("heading", { level: 1 }).textContent()
  await page.getByRole("button", { name: "Back", exact: true }).click()
  await page.getByTestId("project-stack").getByRole("button", { name: `Open ${title}`, exact: true }).click()
  await expect(card).toHaveCount(1)
  await card.getByRole("button", { name: "Now", exact: true }).click()
  await card.getByTestId("ask-submit").click()
  await expect(card).toHaveCount(0)
  await expect(page.getByTestId("transcript").getByText("The answer was received.", { exact: true })).toHaveCount(1)
  await page.getByRole("button", { name: "Back", exact: true }).click()
  await page.getByTestId("project-stack").getByRole("button", { name: `Open ${title}`, exact: true }).click()
  await expect(card).toHaveCount(0)
  await expect(page.getByTestId("transcript").getByText("The answer was received.", { exact: true })).toHaveCount(1)
  await expect(page.locator(".screen-push")).toHaveCSS("opacity", "1")
  await expect(page.locator(".screen-push")).toHaveCSS("transform", /^(none|matrix\(1, 0, 0, 1, 0, 0\))$/)
  await page.screenshot({ path: info.outputPath("original-ask-answered-history.png"), animations: "disabled" })
})
