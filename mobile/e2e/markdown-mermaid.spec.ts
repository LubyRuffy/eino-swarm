import { expect, test } from "@playwright/test"
const source = 'flowchart LR\n'+Array.from({length:8},(_,i)=>`N${i}[Step ${i}] --> N${i+1}[Step ${i+1}]`).join('\n')
test("Mermaid fits the phone, zooms within its frame and preserves source on rewatch",async({page},info)=>{
 await page.setViewportSize({width:320,height:844})
 await page.goto('/?mock=1&tick=0')
 await page.getByRole('button',{name:'返回',exact:true}).click()
 await page.getByRole('button',{name:'打开 Sweep the unused exports',exact:true}).click()
 await page.getByLabel('消息',{exact:true}).fill('```mermaid\n'+source+'\n```')
 await page.locator('form').getByRole('button',{name:'发送',exact:true}).click()
 const diagram=page.getByTestId('phone-mermaid').first()
 const image=diagram.getByRole('img',{name:'Mermaid'})
 await expect(image).toBeVisible()
 await expect.poll(()=>image.evaluate((img:HTMLImageElement)=>img.naturalWidth)).toBeGreaterThan(0)
 await expect(diagram.getByRole('button',{name:'适应窗口',exact:true})).toHaveAttribute('aria-pressed','true')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
 await diagram.getByRole('button',{name:'图原始尺寸',exact:true}).click()
 await expect(diagram.getByLabel('图缩放比例')).toHaveText('100%')
 const viewport=diagram.getByRole('region',{name:'图预览区域'})
 expect(await viewport.evaluate((node)=>node.scrollWidth>node.clientWidth)).toBe(true)
 await viewport.evaluate((node)=>{node.scrollLeft=node.scrollWidth})
 await expect.poll(()=>viewport.evaluate((node)=>node.scrollLeft)).toBeGreaterThan(0)
 await diagram.getByRole('button',{name:'放大图',exact:true}).click()
 await expect(diagram.getByLabel('图缩放比例')).toHaveText('125%')
 await diagram.getByRole('button',{name:'适应窗口',exact:true}).click()
 await diagram.locator('summary').click()
 await expect(diagram.locator('code')).toHaveText(source)
 await page.screenshot({path:info.outputPath('phone-mermaid-fit-source.png')})
 await page.getByRole('button',{name:'返回',exact:true}).click()
 await page.getByRole('button',{name:'打开 Sweep the unused exports',exact:true}).click()
 await expect(page.getByTestId('phone-mermaid').first().getByRole('img',{name:'Mermaid'})).toBeVisible()
})

test("resource-bearing diagrams stay source and make no resource request",async({page})=>{
 let external=0
 await page.route('https://diagram-resource.invalid/**',async(route)=>{external++;await route.abort()})
 await page.goto('/?mock=1&tick=0')
 await page.getByRole('button',{name:'返回',exact:true}).click()
 await page.getByRole('button',{name:'打开 Sweep the unused exports',exact:true}).click()
 const source='flowchart LR\nA@{ img: "https://diagram-resource.invalid/a.png" }'
 await page.getByLabel('消息',{exact:true}).fill('```mermaid\n'+source+'\n```')
 await page.locator('form').getByRole('button',{name:'发送',exact:true}).click()
 await expect(page.locator('code.language-mermaid')).toHaveText(source)
 await expect(page.getByTestId('phone-mermaid')).toHaveCount(0)
 expect(external).toBe(0)
})
