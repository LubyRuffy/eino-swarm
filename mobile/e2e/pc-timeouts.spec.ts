import { expect, test, type Page } from "@playwright/test"
const sheet = (page: Page) => page.getByRole("dialog", { name: "电脑超时", exact: true })
const agent = (page: Page) => sheet(page).getByLabel("子 Agent 总时长（秒）", { exact: true })
const first = (page: Page) => sheet(page).getByLabel("首包等待（秒） · Walkthrough", { exact: true })
const idle = (page: Page) => sheet(page).getByLabel("流空闲等待（秒） · Walkthrough", { exact: true })
const save = (page: Page) => sheet(page).getByRole("button", { name: "保存电脑超时", exact: true })
async function open(page: Page) {
  await page.getByRole("button", { name: "菜单", exact: true }).click()
  await page.getByRole("menuitem", { name: "电脑超时", exact: true }).click()
}
async function start(page: Page, scenario = "") {
  await page.goto("/?mock=1&tick=0" + (scenario ? "&timeouts=" + scenario : ""))
  await page.getByRole("button", { name: "返回", exact: true }).click()
  await open(page)
}
const close = (page: Page) => sheet(page).getByRole("button", { name: "关闭", exact: true }).click()

test("bound PC changes persist on reopen with a independent first-byte preview and explicit old values", async ({ page }, info) => {
  await start(page)
  await expect(agent(page)).toHaveValue("600")
  await expect(save(page)).toBeDisabled()
  await agent(page).fill("3600")
  await first(page).fill("90")
  await idle(page).fill("60")
  await expect(sheet(page).getByText("保存后的首包等待：90 秒。")).toBeVisible()
  await save(page).click()
  await expect(sheet(page).getByText("电脑超时已保存。")).toBeVisible()
  await close(page)
  await open(page)
  await expect(agent(page)).toHaveValue("3600")
  await expect(first(page)).toHaveValue("90")
  await expect(idle(page)).toHaveValue("60")
  await expect(sheet(page).getByText("已保存的首包等待：90 秒。")).toBeVisible()
  await page.screenshot({ path: info.outputPath("saved-PC-timeouts.png") })
})

test("legacy PC feedback remains local without invented editable defaults", async ({ page }, info) => {
  await start(page, "legacy")
  await expect(sheet(page).getByRole("alert")).toHaveText("请更新电脑端以编辑超时。")
  await expect(agent(page)).toHaveCount(0)
  await expect(save(page)).toBeDisabled()
  await page.screenshot({ path: info.outputPath("legacy-PC-timeouts.png") })
  await close(page)
  await expect(page.getByRole("alert")).toHaveCount(0)
  await expect(page.getByTestId("inbox-list")).toBeVisible()
})

test("load retry and invalid seconds do not overwrite existing PC values", async ({ page }) => {
  await start(page, "load-fail")
  await expect(sheet(page).getByRole("alert")).toHaveText("无法加载电脑超时，请重试。")
  await expect(agent(page)).toHaveCount(0)
  await sheet(page).getByRole("button", { name: "重试", exact: true }).click()
  await expect(agent(page)).toHaveValue("600")
  for (const value of ["0", "-1", "1.5", "9223372037"]) {
    await first(page).fill(value)
    await expect(sheet(page).getByRole("alert")).toHaveText("请输入正整数秒数。")
    await expect(save(page)).toBeDisabled()
    await expect(sheet(page).getByText("输入正整数秒数以预览首包等待。")).toBeVisible()
  }
  await close(page); await open(page)
  await expect(first(page)).toHaveValue("30")
})

test("failed save retains edits and supports explicit local retry", async ({ page }, info) => {
  await start(page, "save-fail")
  await agent(page).fill("3600")
  await save(page).click()
  await expect(sheet(page).getByRole("alert")).toHaveText("无法保存电脑超时，请重试。")
  await expect(agent(page)).toHaveValue("3600")
  await expect(save(page)).toBeEnabled()
  await page.screenshot({ path: info.outputPath("retry-PC-timeouts.png") })
  await save(page).click()
  await expect(sheet(page).getByText("电脑超时已保存。")).toBeVisible()
  await close(page); await open(page)
  await expect(agent(page)).toHaveValue("3600")
})

test("Back closes a pending save but late server completion cannot paint a reopened sheet", async ({ page }) => {
  await start(page, "save-slow")
  await agent(page).fill("3600")
  await save(page).click()
  await expect(sheet(page).getByRole("button", { name: "正在保存…", exact: true })).toBeDisabled()
  expect(await page.evaluate(() => (window as Window & { __zwaiAndroidBack?: () => boolean }).__zwaiAndroidBack?.())).toBe(true)
  await expect(sheet(page)).toHaveCount(0)
  expect(await page.evaluate(() => (window as Window & { __zwaiAndroidBack?: () => boolean }).__zwaiAndroidBack?.())).toBe(false)
  await open(page)
  await expect(agent(page)).toHaveValue("600")
  await page.waitForTimeout(1400)
  await expect(agent(page)).toHaveValue("600")
  await expect(sheet(page).getByText("电脑超时已保存。")).toHaveCount(0)
  await close(page); await open(page)
  await expect(agent(page)).toHaveValue("3600")
})

test("empty PC providers leave worker controls reachable on a narrow iPhone", async ({ page }, info) => {
  await start(page, "empty")
  await page.setViewportSize({ width: 320, height: 844 })
  await expect(sheet(page).getByText("此电脑尚未配置模型服务。")).toBeVisible()
  await agent(page).fill("3600")
  const box = await save(page).boundingBox()
  expect(box).not.toBeNull(); expect(box!.x).toBeGreaterThanOrEqual(0); expect(box!.x + box!.width).toBeLessThanOrEqual(320)
  await save(page).click()
  await expect(sheet(page).getByText("电脑超时已保存。")).toBeVisible()
  await page.screenshot({ path: info.outputPath("empty-PC-timeouts-narrow.png") })
})
