import { expect, test } from "@playwright/test"

test("phone confirms the selected host and waits for the replacement to finish restoring", async ({ page }, info) => {
  await page.goto("/?mock=1&tick=0&host-update=1")
  const update = page.getByTestId("host-update")
  const button = update.getByRole("button", { name: "升级这台主机" })
  const status = update.getByRole("status")
  await expect(status).toHaveText("Walkthrough PC 有新版本 · 1.2.3 → 1.2.4")
  await button.click()
  const dialog = page.getByRole("dialog", { name: "升级 Walkthrough PC？" })
  await expect(dialog.getByText("1.2.3 → 1.2.4")).toBeVisible()
  await dialog.getByRole("button", { name: "取消" }).click()
  await expect(status).toHaveText("Walkthrough PC 有新版本 · 1.2.3 → 1.2.4")
  await button.click()
  await page.screenshot({ path: info.outputPath("host-update-confirmation.png") })
  await dialog.getByRole("button", { name: "确认升级" }).click()
  await expect(update.getByRole("progressbar")).toHaveAttribute("value", "40")
  await expect(status).toHaveText("等待主机完成恢复…")
  await page.screenshot({ path: info.outputPath("host-update-restoring.png") })
  await expect(status).toHaveText("主机升级完成")
  await page.screenshot({ path: info.outputPath("host-update-completed.png") })
})

test("an unsupported host only explains the Linux recovery requirements when asked", async ({ page }) => {
  await page.goto("/?mock=1&tick=0")
  const update = page.getByTestId("host-update")
  await expect(update).toHaveCount(0)
  await page.getByRole("button", { name: "返回", exact: true }).click()
  await page.getByRole("button", { name: "菜单", exact: true }).click()
  await page.getByRole("menuitem", { name: "检查这台主机的更新" }).click()
  await expect(update.getByRole("status")).toHaveText("Walkthrough PC 暂不支持远程升级。Linux 需要受保护的开机服务和支持该功能的版本。")
  await expect(update.getByRole("button", { name: "升级这台主机" })).toHaveCount(0)
})

test("the pending host reason can be hidden and checked again without retrying the install", async ({ page }) => {
  await page.goto("/?mock=1&tick=0&host-update=pending")
  await page.getByRole("button", { name: "返回", exact: true }).click()
  const update = page.getByTestId("host-update")
  await update.getByRole("button", { name: "升级这台主机" }).click()
  await page.getByRole("dialog").getByRole("button", { name: "确认升级" }).click()
  await expect(update.getByRole("status")).toHaveText("Waiting for the new process to publish its lease.")
  await expect(update.getByRole("button", { name: "重试" })).toHaveCount(0)
  await update.getByRole("button", { name: "关闭" }).click()
  await expect(update).toHaveCount(0)
  await page.getByRole("button", { name: "菜单", exact: true }).click()
  await page.getByRole("menuitem", { name: "检查这台主机的更新" }).click()
  await expect(update.getByRole("status")).toHaveText("Waiting for the new process to publish its lease.")
})
