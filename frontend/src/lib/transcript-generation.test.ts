import { describe, expect, it } from "vitest"
import { emptyTranscript, reduceEvent, reduceEvents } from "./transcript"
import type { SwarmEvent } from "./types"

function event(kind: string, seq: number, extra: Partial<SwarmEvent> = {}): SwarmEvent {
  return { thread_id: "thread", turn_id: "turn", agent_id: "worker", kind, seq, text: "", created_at: "2026-10-22T00:00:00Z", ...extra }
}
const interrupted = event("generation_interrupted", 4, { message_id: "first", text: JSON.stringify({ reason: "engine_restart", detail: "handoff", recovery: "pending" }) })
const recovered = event("generation_recovered", 6, { ...interrupted, kind: "generation_recovered", seq: 6, text: JSON.stringify({ reason: "engine_restart", detail: "handoff", recovery: "recovered" }) })
const thought = event("reasoning_delta", 0, { message_id: "first", text: "partial thought" })

describe("generation interruption", () => {
  it("closes one generation without failing its recovering worker and preserves the reason after recovery", () => {
    let state = reduceEvents(emptyTranscript(), [event("spawned", 1), thought, interrupted])
    expect(state.agents.worker.status).toBe("running")
    expect(state.agents.worker.blocks.find((b) => b.kind === "reasoning")?.streaming).toBe(false)
    expect(state.agents.worker.blocks.find((b) => b.kind === "notice")?.generation).toMatchObject({ reason: "engine_restart", recovery: "pending" })
    state = reduceEvents(state, [recovered, event("reasoning_delta", 0, { message_id: "second", text: "partial thought" })])
    expect(state.agents.worker.blocks.filter((b) => b.kind === "reasoning").map((b) => b.streaming)).toEqual([false, true])
    expect(state.agents.worker.blocks.filter((b) => b.generation)).toHaveLength(1)
    expect(state.agents.worker.blocks.find((b) => b.generation)?.generation?.recovery).toBe("recovered")
  })
  it.each([false, true])("cannot reopen an interrupted output with a late delta (notice first: %s)", (noticeFirst) => {
    const events = noticeFirst ? [interrupted, thought] : [thought, interrupted, { ...thought, text: "partial thought extended" }]
    const state = reduceEvents(emptyTranscript(), events)
    expect(state.agents.worker.blocks.find((b) => b.kind === "reasoning")?.streaming).toBe(false)
  })
  it("keeps recovered authoritative over a stale interruption without reviving a finished worker", () => {
    const state = reduceEvents(emptyTranscript(), [thought, recovered, interrupted, event("finished", 8, { text: "result" }), recovered])
    expect(state.agents.worker.status).toBe("done")
    expect(state.agents.worker.blocks.filter((b) => b.generation)).toHaveLength(1)
    expect(state.agents.worker.blocks.find((b) => b.generation)?.generation?.recovery).toBe("recovered")
  })
  it.each(["resumed", "restart_resumed", "spawned"])("seals legacy thinking at %s and names the missing cause honestly", (kind) => {
    const state = reduceEvents(emptyTranscript(), [event("spawned", 1), event("reasoning_delta", 0, { text: "old thought" }), event(kind, 5, { agent_id: kind === "spawned" ? "worker" : "manager" })])
    const worker = state.agents.worker
    expect(worker.status).toBe("running")
    expect(worker.blocks.find((b) => b.kind === "reasoning")?.streaming).toBe(false)
    expect(worker.blocks.find((b) => b.generation)?.generation).toMatchObject({ reason: "unknown", recovery: "recovered" })
  })
  it("does not paint internal generation bookkeeping or mutate an earlier state", () => {
    const before = reduceEvent(emptyTranscript(), thought)
    const after = reduceEvent(before, interrupted)
    expect(before.agents.worker.blocks[0].streaming).toBe(true)
    expect(after.agents.worker.blocks[0].streaming).toBe(false)
    for (const kind of ["generation_started", "generation_completed"]) {
      expect(reduceEvent(emptyTranscript(), event(kind, 3)).agentOrder).toEqual([])
    }
  })
})

it.each(["resumed", "restart_resumed", "spawned"])("does not invent interruptions for a completed legacy thought at %s", (kind) => {
  const state = reduceEvents(emptyTranscript(), [event("spawned", 1), event("reasoning", 2, { text: "completed thought" }), event("finished", 3, { text: "done" }), event(kind, 5, { agent_id: kind === "spawned" ? "worker" : "manager" })])
  expect(state.agents.worker.blocks.some((b) => b.generation)).toBe(false)
})

it("seals only arguments still being generated by the interrupted output", () => {
  const state = reduceEvents(emptyTranscript(), [
    event("tool_call_delta", 0, { message_id: "first", tool_call_id: "writing", text: "read(8)" }),
    event("tool_call", 2, { message_id: "other", tool_call_id: "executing", text: "read({})" }), interrupted,
  ])
  expect(state.agents.worker.blocks.find((b) => b.tool?.callId === "writing")?.tool?.pending).toBe(false)
  expect(state.agents.worker.blocks.find((b) => b.tool?.callId === "executing")?.tool?.pending).toBe(true)
})

it("does not revive a finished worker when an interrupted generation sends a buffered delta", () => {
  const state = reduceEvents(emptyTranscript(), [thought, interrupted, event("finished", 7, { text: "completed" }), { ...thought, text: "partial thought extended" }])
  expect(state.agents.worker.status).toBe("done")
  expect(state.agents.worker.blocks.find((b) => b.kind === "reasoning")?.streaming).toBe(false)
})

it.each(["reasoning_delta", "delta"])("does not close replacement thinking when the first old %s arrives after its notice", (kind) => {
  const state = reduceEvents(emptyTranscript(), [interrupted, event("reasoning_delta", 0, { message_id: "second", text: "replacement thought" }), { ...thought, kind }])
  expect(state.agents.worker.blocks.find((b) => b.messageId === "second" && b.kind === "reasoning")?.streaming).toBe(true)
  expect(state.agents.worker.blocks.find((b) => b.messageId === "first" && !b.generation)?.streaming).toBe(false)
})

it.each(["resumed", "restart_resumed", "spawned"])("seals a pre-lifecycle identified legacy stream at %s without inventing its cause", (kind) => {
  const state = reduceEvents(emptyTranscript(), [event("spawned", 1), thought, event(kind, 5, { agent_id: kind === "spawned" ? "worker" : "manager" }), { ...thought, text: "partial thought extended" }])
  expect(state.agents.worker.blocks.find((b) => b.kind === "reasoning")?.streaming).toBe(false)
  expect(state.agents.worker.blocks.find((b) => b.generation)).toMatchObject({ messageId: "first", generation: { reason: "unknown", recovery: "recovered" } })
})

it("uses a late recorded cause while retaining the observed recovery of an upgraded stream", () => {
  const state = reduceEvents(emptyTranscript(), [thought, event("resumed", 6, { agent_id: "manager" }), interrupted])
  expect(state.agents.worker.blocks.filter((b) => b.generation)).toHaveLength(1)
  expect(state.agents.worker.blocks.find((b) => b.generation)?.generation).toMatchObject({ reason: "engine_restart", recovery: "recovered" })
})
