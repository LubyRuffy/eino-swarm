func TestSteerTrailingGoalReopensACompletedObjectiveOnTheSameTurn(t *testing.T) {
	provider.SetCompleteOpenGoal(false)
	t.Cleanup(func() { provider.SetCompleteOpenGoal(true) })
	e := newTestEngine(t)
	th, _ := e.CreateThread("goal steer", "", "")
	logGoalSteerFailure(t, e, th.ID)
	if err := e.SetThreadGoal(th.ID, "previous objective"); err != nil {
		t.Fatal(err)
	}
	if err := e.CompleteThreadGoal(th.ID, ""); err != nil {
		t.Fatal(err)
	}
	first, err := e.StartTurn(th.ID, "Inspect the current operation.")
	if err != nil {
		t.Fatal(err)
	}
	for _, text := range []string{"Continue the assigned operation /goal", "/goal Continue the assigned operation"} {
		if err := e.Steer(th.ID, text); err != nil {
			t.Fatal(err)
		}
		got, err := e.Store().GetThread(th.ID)
		if err != nil || got.Goal != "Continue the assigned operation" || got.GoalComplete || got.GoalBlocked || got.GoalCapped || got.GoalIdle {
			t.Fatalf("goal not reopened: %+v err=%v", got, err)
		}
		if e.Status(th.ID).TurnID != first.ID {
			t.Fatal("goal steer must not replace the current turn")
		}
	}
	if err := e.Interrupt(th.ID); err != nil {
		t.Fatal(err)
	}
	waitSettled(t, e, th.ID)
}

// The edit notice is generated by the engine. Its objective remains literal
// even when the user explicitly saved text that resembles a command marker.
func TestGoalEditSteerDoesNotInterpretTheSavedObjectiveAgain(t *testing.T) {
	e := newTestEngine(t)
	th, _ := e.CreateThread("literal goal", "", "")
	logGoalSteerFailure(t, e, th.ID)
	if _, err := e.StartTurn(th.ID, "Inspect the operation."); err != nil {
		t.Fatal(err)
	}
	const objective = "Inspect literal command /goal"
	if err := e.SetThreadGoal(th.ID, objective); err != nil {
		t.Fatal(err)
	}
	got, err := e.Store().GetThread(th.ID)
	if err != nil || got.Goal != objective {
		t.Fatalf("generated steer reinterpreted the saved objective: %+v err=%v", got, err)
	}
	if err := e.Interrupt(th.ID); err != nil {
		t.Fatal(err)
	}
	waitSettled(t, e, th.ID)
}

// A timeout once occurred only in the full serial race suite. Preserve the
// actual run boundary on recurrence without changing steering/Stop timing.
func logGoalSteerFailure(t *testing.T, e *Engine, threadID string) {
	t.Helper()
	t.Cleanup(func() {
		if !t.Failed() {
			return
		}
		stack := make([]byte, 1<<20)
		n := goruntime.Stack(stack, true)
		t.Logf("goal steer goroutines:\n%s", stack[:n])
		t.Logf("goal steer runtime: %+v", e.Status(threadID))
		thread, err := e.Store().GetThread(threadID)
		t.Logf("goal steer thread: %+v err=%v", thread, err)
		turns, err := e.Store().ListTurns(threadID)
		t.Logf("goal steer turn count: %d err=%v", len(turns), err)
		for _, turn := range turns {
			t.Logf("goal steer turn: %+v", turn)
		}
		events, err := e.Replay(threadID, 0)
		t.Logf("goal steer Trace: %+v err=%v", events, err)
	})
}
